  /**
   * Injects the missing window.notebookAppApi host bridge and removes CSP blocks
   * so raw Google NotebookLM Angular bundles don't crash when opened locally.
   */
  public static injectNotebookAppApiPolyfill(rawHtml: string): string {
    if (!rawHtml) return '';
    let html = rawHtml.replace(/<meta\s+http-equiv=["']Content-Security-Policy["'][^>]*>/gi, '');
    const polyfillScript = `
<script>
window.notebookAppApi = {
  clientType: 'notebooklm-web',
  addThemeChangeListener: function(cb) { try { cb('light'); } catch(e){} },
  notifyAppReady: function() {},
  dispatchLogEvent: function() {}
};
</script>
`;
    if (html.includes('</head>')) {
      return html.replace('</head>', `${polyfillScript}</head>`);
    }
    return polyfillScript + html;
  }
