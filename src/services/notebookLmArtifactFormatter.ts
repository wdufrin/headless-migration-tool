  /**
   * Extracts structured JSON data (quiz questions or flashcards) from an artifact or its raw HTML.
   */
  public static extractAppData(artifact: any): { quiz?: any[]; flashcards?: any[]; topics?: string[] } | null {
    if (!artifact) return null;
    const rawApp = artifact.rawArtifact?.app || artifact.app;
    if (rawApp?.appData) {
      try {
        const parsed = typeof rawApp.appData === 'string' ? JSON.parse(rawApp.appData) : rawApp.appData;
        if (parsed && (parsed.quiz || parsed.flashcards)) return parsed;
      } catch {}
    }

    const appHtml = rawApp?.appHtml || artifact.content;
    if (typeof appHtml === 'string') {
      const match = appHtml.match(/data-app-data="([^"]+)"/);
      if (match) {
        try {
          const decoded = match[1]
            .replace(/&quot;/g, '"')
            .replace(/&#39;/g, "'")
            .replace(/&amp;/g, '&')
            .replace(/&lt;/g, '<')
            .replace(/&gt;/g, '>');
          return JSON.parse(decoded);
        } catch {}
      }
    }
    return null;
  }

  /**
   * Formats a structured Quiz into readable Markdown with questions, options, answer key, and rationales.
   */
  public static formatQuizMarkdown(title: string, notebookName: string, quizList: any[]): string {
    let md = `# Quiz: ${title}\n\n- **Notebook:** ${notebookName}\n- **Total Questions:** ${quizList.length}\n\n---\n\n`;
    quizList.forEach((q: any, idx: number) => {
      md += `### Question ${idx + 1}\n\n${q.question}\n\n`;
      const options = q.answerOptions || [];
      options.forEach((opt: any, optIdx: number) => {
        const letter = String.fromCharCode(65 + optIdx);
        const check = opt.isCorrect ? '[x]' : '[ ]';
        const correctTag = opt.isCorrect ? ' **(Correct Answer)**' : '';
        md += `- ${check} **${letter}.** ${opt.text}${correctTag}\n`;
        if (opt.isCorrect && opt.rationale) {
          md += `  - *Rationale:* ${opt.rationale}\n`;
        }
      });
      if (q.hint) {
        md += `\n*Hint:* ${q.hint}\n`;
      }
      md += `\n---\n\n`;
    });
    return md.trim();
  }

  /**
   * Formats structured Flashcards into a clean Markdown table with Front (Prompt) and Back (Answer).
   */
  public static formatFlashcardsMarkdown(title: string, notebookName: string, flashcardsList: any[]): string {
    let md = `# Flashcards: ${title}\n\n- **Notebook:** ${notebookName}\n- **Total Cards:** ${flashcardsList.length}\n\n---\n\n`;
    md += `| # | Prompt / Question | Answer |\n|---|---|---|\n`;
    flashcardsList.forEach((card: any, idx: number) => {
      const front = (card.f || card.front || '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
      const back = (card.b || card.back || '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
      md += `| ${idx + 1} | ${front} | ${back} |\n`;
    });
    return md.trim();
  }

